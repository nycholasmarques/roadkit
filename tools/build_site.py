#!/usr/bin/env python3
"""Builds the GitHub Pages site into a folder (stdlib only).

    python3 tools/build_site.py _site [--version 1.10.0]

  _site/            the landing page (site/), with the icons and the images it uses
  _site/app/        the Roadkit app itself as static files, with the examples: the live demo. With no server
                    behind it, progress stays in the browser (the app's "local" mode), and a banner says so.

The version printed on the page comes from --version, else ROADKIT_VERSION, else the latest git tag.
"""
import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import roadkit  # noqa: E402

ICONS = ["icon.svg", "favicon.svg", "icon-192.png", "apple-touch-icon.png"]
MEDIA = ["visao-geral.gif", "mapa-claro.png", "mapa-escuro.png", "kanban.png", "hoje.png", "projetos.png",
         "estatisticas.png", "estatisticas-escuro.png", "notas.png", "temas.png", "celular.png"]


def version(arg):
    v = arg or os.environ.get("ROADKIT_VERSION", "")
    if not v:
        try:
            v = subprocess.run(["git", "describe", "--tags", "--abbrev=0"], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()
        except (OSError, subprocess.CalledProcessError):
            v = "dev"
    return v.lstrip("v")


def build(out, ver):
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(ROOT / "site", out)
    (out / "icons").mkdir()
    for f in ICONS:
        shutil.copy2(ROOT / "src" / "icons" / f, out / "icons" / f)
    (out / "media").mkdir()
    for f in MEDIA:
        shutil.copy2(ROOT / "docs" / "media" / f, out / "media" / f)
    page = out / "index.html"
    page.write_text(page.read_text("utf-8").replace("__ROADKIT_VERSION__", ver), "utf-8")

    # the demo: the app as static files, with only the examples and a manifest that says it is a demo
    app = out / "app"
    app.mkdir()
    shutil.copy2(ROOT / "index.html", app / "index.html")
    shutil.copytree(ROOT / "src", app / "src", ignore=shutil.ignore_patterns("sw.js"))
    shutil.copytree(ROOT / "examples", app / "examples")
    manifest = json.loads(roadkit.manifest_text(False))
    manifest["roadmaps"] = [r for r in manifest["roadmaps"] if r["group"].startswith("examples/")]
    manifest["groups"] = [g for g in manifest["groups"] if g["id"].startswith("examples/")]
    manifest["demo"] = True
    manifest["_note"] = "Generated by tools/build_site.py for the demo on GitHub Pages."
    (app / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", "utf-8")
    # the worker lives next to the page here (the server serves src/sw.js at the root; Pages cannot)
    sw = (ROOT / "src" / "sw.js").read_text("utf-8").replace("__ROADKIT_VERSION__", roadkit.app_version())
    (app / "sw.js").write_text(sw, "utf-8")

    # the examples the landing page lists, light enough to fetch on load
    examples = [{k: r.get(k) for k in ("id", "title", "description", "icon", "language", "topics", "projects")} for r in manifest["roadmaps"]]
    (out / "examples.json").write_text(json.dumps(examples, ensure_ascii=False, indent=2) + "\n", "utf-8")
    (out / ".nojekyll").write_text("")   # serve the folders as they are
    return len(examples)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--version")
    a = ap.parse_args()
    ver = version(a.version)
    n = build(Path(a.out).resolve(), ver)
    print(f"site built in {a.out} (version {ver}, {n} example roadmaps in the demo)")


if __name__ == "__main__":
    main()
